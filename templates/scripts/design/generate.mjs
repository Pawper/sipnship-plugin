// Generates every platform's design tables from design/tokens.json and
// design/icons.json: the one source of the look, so a web screen and an
// Android or iOS screen read the same values and a change is one line.
// Usage: node scripts/design/generate.mjs [--check]
//   (no flag) writes the files named under "outputs" in tokens.json
//   --check   exits 1 when any of them is out of date, writes nothing
// Where design/copy/ exists (scripts/design/copy-extract.mjs writes it from
// the mocks), it also writes the copy modules outputs.copyTs, copyKotlin and
// copySwift name: the words of every screen, by screen and id.
// Type roles come out as named styles on each platform: a CSS class
// .type-<role> with its variables, a TypeScript ROLES entry, a Kotlin
// DesignType.<Role>, a Swift Design.Type.<role>. A screen says the role.
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const read = (p) => JSON.parse(readFileSync(join(root, p), "utf8"));
const tokens = read("design/tokens.json");
let icons = { icons: [] };
try { icons = read("design/icons.json"); } catch {}
const out = tokens.outputs || {};
const header = "Generated by scripts/design/generate.mjs from design/tokens.json and design/icons.json. Do not edit; change the source and regenerate.";

const j = (v) => JSON.stringify(v);
const cap = (s) => s[0].toUpperCase() + s.slice(1);
const kebab = (s) => s.replace(/[A-Z]/g, (m) => "-" + m.toLowerCase());
const dbl = (n) => (Number.isInteger(n) ? n + ".0" : String(n));
const argb = (hex) => "0xFF" + hex.slice(1).toUpperCase();
const ktStr = (s) => '"' + String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\$/g, "\\$") + '"';
const swStr = (s) => '"' + String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"') + '"';
const accent = (key) => (tokens.accents || []).find((a) => a.key === key);
const family = (key) => (tokens.type.families || []).find((f) => f.key === key);
const ground = tokens.ground || [], accents = tokens.accents || [], gradients = tokens.gradients || [];
const families = tokens.type.families || [], roles = tokens.type.roles || [];
const radii = tokens.radii || {}, spacing = tokens.spacing || {}, iconSizes = tokens.iconSizes || {};
const blocks = Object.fromEntries(Object.entries(tokens.blocks || {}).filter(([k]) => !k.startsWith("_")));
const colors = Object.fromEntries([...ground.map((c) => [c.key, c.hex]), ...accents.flatMap((a) => a.stops.map((s, i) => [`${a.key}-${i + 1}`, s]))]);
const gradientCss = (g) => `linear-gradient(${g.direction}, ${accent(g.accent).stops.map((s, i) => `${s} ${g.offsets[i]}%`).join(", ")})`;

// ---------- TypeScript
const ts = `// ${header}

export interface TypeRole { family: string; size: number; weight: number; lineHeight: number; letterSpacing: number; uppercase: boolean; }
export interface IconPart { path: string; filled?: boolean; strokeWidth?: number; opacity?: number; }
export interface DesignIcon { key: string; name: string; group: string; size: number; strokeWidth: number; parts: IconPart[]; }

/** Every colour by key: ground by key, accents as key-1 to key-3. */
export const COLORS: Readonly<Record<string, string>> = ${j(colors)};
export const GROUND = ${j(ground)} as const;
export const ACCENTS = ${j(accents)} as const;
export const GRADIENTS: Readonly<Record<string, string>> = ${j(Object.fromEntries(gradients.map((g) => [g.key, gradientCss(g)])))};
export const FAMILIES = ${j(families)} as const;
/** The type roles by key: a screen names a role, never a size. */
export const ROLES: Readonly<Record<string, TypeRole>> = ${j(Object.fromEntries(roles.map((r) => [r.key, { family: r.family, size: r.size, weight: r.weight, lineHeight: r.lineHeight, letterSpacing: r.letterSpacing ?? 0, uppercase: !!r.uppercase }])))};
export const RADII: Readonly<Record<string, number>> = ${j(radii)};
export const SPACING: Readonly<Record<string, number>> = ${j(spacing)};
export const ICON_SIZES: Readonly<Record<string, number>> = ${j(iconSizes)};
/** Per-feature design values, one object per block. */
export const BLOCKS = ${j(blocks)} as const;
export const ICONS: readonly DesignIcon[] = ${j(icons.icons)};
export const ICON_KEYS: readonly string[] = ${j(icons.icons.map((i) => i.key))};
`;

// ---------- CSS
const fontBase = out.fontUrlBase || "/fonts/";
const css = `/* ${header} */
${families.filter((f) => f.file).map((f) => `@font-face {
  font-family: "${f.name}";
  src: url("${fontBase}${f.file}");
  font-weight: ${f.weights && f.weights.length > 1 ? `${Math.min(...f.weights)} ${Math.max(...f.weights)}` : (f.weights ? f.weights[0] : 400)};
  font-display: swap;
}`).join("\n")}
:root {
${ground.map((c) => `  --${c.key}: ${c.hex.toLowerCase()};`).join("\n")}
${accents.flatMap((a) => a.stops.map((s, i) => `  --${a.key}-${i + 1}: ${s.toLowerCase()};`)).join("\n")}
${gradients.map((g) => `  --gradient-${g.key}: linear-gradient(${g.direction}, ${g.offsets.map((o, i) => `var(--${g.accent}-${i + 1}) ${o}%`).join(", ")});`).join("\n")}
${families.map((f) => `  --font-${f.key}: "${f.name}", ${f.fallback};`).join("\n")}
${roles.flatMap((r) => [`  --type-${r.key}-family: var(--font-${r.family});`, `  --type-${r.key}-size: ${r.size}px;`, `  --type-${r.key}-weight: ${r.weight};`, `  --type-${r.key}-leading: ${r.lineHeight};`, `  --type-${r.key}-spacing: ${r.letterSpacing ?? 0}em;`]).join("\n")}
${Object.entries(radii).map(([k, v]) => `  --radius-${kebab(k)}: ${v}px;`).join("\n")}
${Object.entries(spacing).map(([k, v]) => `  --space-${kebab(k)}: ${v}px;`).join("\n")}
${Object.entries(iconSizes).map(([k, v]) => `  --icon-${kebab(k)}: ${v}px;`).join("\n")}
${Object.entries(blocks).flatMap(([b, vals]) => Object.entries(vals).map(([k, v]) => `  --${kebab(b)}-${kebab(k)}: ${typeof v === "number" ? v + "px" : v};`)).join("\n")}
}
${roles.map((r) => `.type-${r.key} { font-family: var(--type-${r.key}-family); font-size: var(--type-${r.key}-size); font-weight: var(--type-${r.key}-weight); line-height: var(--type-${r.key}-leading); letter-spacing: var(--type-${r.key}-spacing);${r.uppercase ? " text-transform: uppercase;" : ""} }`).join("\n")}
`;

// ---------- Kotlin
const kt = (pkg) => `package ${pkg}

// ${header}

data class DesignIconPart(val path: String, val filled: Boolean = false, val strokeWidth: Double? = null, val opacity: Double? = null)
data class DesignIcon(val key: String, val name: String, val group: String, val size: Int, val strokeWidth: Double, val parts: List<DesignIconPart>)
/** A type role: family key, size in sp, weight, line height, letter spacing in em, uppercase or not. */
data class DesignRole(val family: String, val size: Int, val weight: Int, val lineHeight: Double, val letterSpacing: Double, val uppercase: Boolean)

/** Ground and accent colours as ARGB. */
object DesignColors {
${ground.map((c) => `    const val ${cap(c.key)}: Long = ${argb(c.hex)}`).join("\n")}
${accents.flatMap((a) => a.stops.map((s, i) => `    const val ${cap(a.key)}${i + 1}: Long = ${argb(s)}`)).join("\n")}
}

/** Gradient stops, top to bottom, as ARGB. */
object DesignGradients {
${gradients.map((g) => `    val ${cap(g.key)}: List<Long> = listOf(${accent(g.accent).stops.map(argb).join(", ")})`).join("\n")}
}

/** The type roles, as design/tokens.json names them: a screen says the role. */
object DesignType {
${roles.map((r) => `    val ${cap(r.key)} = DesignRole(${ktStr(r.family)}, ${r.size}, ${r.weight}, ${dbl(r.lineHeight)}, ${dbl(r.letterSpacing ?? 0)}, ${!!r.uppercase})`).join("\n")}
}

/** Radii, spacing and icon sizes in dp. */
object DesignRadii {
${Object.entries(radii).map(([k, v]) => `    const val ${cap(k)}: Int = ${v}`).join("\n")}
}
object DesignSpacing {
${Object.entries(spacing).map(([k, v]) => `    const val ${cap(k)}: Int = ${v}`).join("\n")}
}
object DesignIconSizes {
${Object.entries(iconSizes).map(([k, v]) => `    const val ${cap(k)}: Int = ${v}`).join("\n")}
}

/** Per-feature design values, one object per block. */
object DesignBlocks {
${Object.entries(blocks).map(([b, vals]) => `    object ${cap(b)} {\n${Object.entries(vals).map(([k, v]) => `        ${typeof v === "number" ? `const val ${cap(k)}: ${Number.isInteger(v) ? "Int" : "Double"} = ${v}` : `const val ${cap(k)}: String = ${ktStr(v)}`}`).join("\n")}\n    }`).join("\n")}
}

/** Font files in design/fonts, by family key. */
val FONT_FILES: Map<String, String> = mapOf(
${families.filter((f) => f.file).map((f) => `    ${ktStr(f.key)} to ${ktStr(f.file)},`).join("\n")}
)

val ICONS: List<DesignIcon> = listOf(
${icons.icons.map((i) => `    DesignIcon(${ktStr(i.key)}, ${ktStr(i.name)}, ${ktStr(i.group || "interface")}, ${i.size}, ${dbl(i.strokeWidth)}, listOf(\n${i.parts.map((p) => `        DesignIconPart(${[ktStr(p.path), p.filled ? "filled = true" : null, p.strokeWidth !== undefined ? "strokeWidth = " + dbl(p.strokeWidth) : null, p.opacity !== undefined ? "opacity = " + dbl(p.opacity) : null].filter(Boolean).join(", ")}),`).join("\n")}\n    )),`).join("\n")}
)

val ICON_KEYS: List<String> = ICONS.map { it.key }
`;

// ---------- Swift
const swift = `// ${header}
import Foundation

public enum Design {
    public struct Role { public let family: String; public let size: Double; public let weight: Int; public let lineHeight: Double; public let letterSpacing: Double; public let uppercase: Bool }
    public struct IconPart { public let path: String; public let filled: Bool; public let strokeWidth: Double?; public let opacity: Double? }
    public struct Icon { public let key: String; public let name: String; public let group: String; public let size: Double; public let strokeWidth: Double; public let parts: [IconPart] }

    /** Colours as hex strings; ground by key, accents as key1 to key3. */
    public enum Colors {
${ground.map((c) => `        public static let ${c.key} = ${swStr(c.hex)}`).join("\n")}
${accents.flatMap((a) => a.stops.map((s, i) => `        public static let ${a.key}${i + 1} = ${swStr(s)}`)).join("\n")}
    }
    public enum Gradients {
${gradients.map((g) => `        public static let ${g.key}: [String] = [${accent(g.accent).stops.map(swStr).join(", ")}]`).join("\n")}
    }
    /** The type roles: a screen says the role. */
    public enum Type {
${roles.map((r) => `        public static let ${r.key} = Role(family: ${swStr(r.family)}, size: ${dbl(r.size)}, weight: ${r.weight}, lineHeight: ${dbl(r.lineHeight)}, letterSpacing: ${dbl(r.letterSpacing ?? 0)}, uppercase: ${!!r.uppercase})`).join("\n")}
    }
    public enum Radii {
${Object.entries(radii).map(([k, v]) => `        public static let ${k}: Double = ${dbl(v)}`).join("\n")}
    }
    public enum Spacing {
${Object.entries(spacing).map(([k, v]) => `        public static let ${k}: Double = ${dbl(v)}`).join("\n")}
    }
    public enum IconSizes {
${Object.entries(iconSizes).map(([k, v]) => `        public static let ${k}: Double = ${dbl(v)}`).join("\n")}
    }
    public enum Blocks {
${Object.entries(blocks).map(([b, vals]) => `        public enum ${cap(b)} {\n${Object.entries(vals).map(([k, v]) => `            public static let ${k}${typeof v === "number" ? `: Double = ${dbl(v)}` : ` = ${swStr(v)}`}`).join("\n")}\n        }`).join("\n")}
    }
    public static let fontFiles: [String: String] = [${families.filter((f) => f.file).map((f) => `${swStr(f.key)}: ${swStr(f.file)}`).join(", ") || ":"}]
    public static let icons: [Icon] = [
${icons.icons.map((i) => `        Icon(key: ${swStr(i.key)}, name: ${swStr(i.name)}, group: ${swStr(i.group || "interface")}, size: ${dbl(i.size)}, strokeWidth: ${dbl(i.strokeWidth)}, parts: [${i.parts.map((p) => `IconPart(path: ${swStr(p.path)}, filled: ${!!p.filled}, strokeWidth: ${p.strokeWidth !== undefined ? dbl(p.strokeWidth) : "nil"}, opacity: ${p.opacity !== undefined ? dbl(p.opacity) : "nil"})`).join(", ")}]),`).join("\n")}
    ]
}
`;

// ---------- Copy: the words of every mocked screen, from design/copy/*.json
// (which scripts/design/copy-extract.mjs writes from design/mocks/). A
// screen says copy.home.welcomeBack (TypeScript), Copy.Home.WelcomeBack
// (Kotlin) or Copy.Home.welcomeBack (Swift), never the words.
const copyDir = join(root, "design", "copy");
const copyHeader = "Generated by scripts/design/generate.mjs from design/copy/*.json, which scripts/design/copy-extract.mjs writes from design/mocks/. Do not edit; change the mock and run both.";
const camel = (s) => {
  const words = String(s).split(/[^A-Za-z0-9]+/).filter(Boolean);
  const c = words.map((w, i) => (i ? w[0].toUpperCase() + w.slice(1) : w[0].toLowerCase() + w.slice(1))).join("") || "text";
  return /^[0-9]/.test(c) ? "_" + c : c;
};
const unique = (names) => { const seen = new Map(); return names.map((n) => { const k = seen.get(n) || 0; seen.set(n, k + 1); return k ? `${n}${k + 1}` : n; }); };
const KT_KEYWORDS = new Set(["as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface", "is", "null", "object", "package", "return", "super", "this", "throw", "true", "try", "typealias", "typeof", "val", "var", "when", "while"]);
const SW_KEYWORDS = new Set(["as", "break", "case", "catch", "class", "continue", "default", "defer", "do", "else", "enum", "extension", "false", "for", "func", "guard", "if", "import", "in", "init", "is", "let", "nil", "protocol", "public", "repeat", "return", "self", "static", "struct", "super", "switch", "throw", "true", "try", "var", "where", "while", "Type", "Self"]);
const ktName = (n) => (KT_KEYWORDS.has(n) ? "`" + n + "`" : n);
const swName = (n) => (SW_KEYWORDS.has(n) ? "`" + n + "`" : n);
let copyScreens = [];
if (existsSync(copyDir)) {
  const files = readdirSync(copyDir).filter((f) => f.endsWith(".json")).sort();
  const names = unique(files.map((f) => camel(f.replace(/\.json$/, ""))));
  copyScreens = files.map((f, i) => {
    const doc = JSON.parse(readFileSync(join(copyDir, f), "utf8"));
    const ids = Object.keys(doc).filter((k) => !k.startsWith("_"));
    const keys = unique(ids.map(camel));
    return { name: names[i], strings: ids.map((id, k) => [keys[k], String(doc[id])]) };
  });
}
const copyTs = `// ${copyHeader}

/** Every string on every mocked screen, by screen and id: a screen says copy.<screen>.<id>, never the words. */
export const copy = {
${copyScreens.map((s) => `  ${s.name}: {\n${s.strings.map(([k, v]) => `    ${k}: ${j(v)},`).join("\n")}\n  },`).join("\n")}
} as const;

export type CopyScreen = keyof typeof copy;
`;
const copyKt = (pkg) => `package ${pkg}

// ${copyHeader}

/** Every string on every mocked screen, by screen and id: a screen says Copy.<Screen>.<Id>, never the words. */
object Copy {
${copyScreens.map((s) => `    object ${ktName(cap(s.name))} {\n${s.strings.map(([k, v]) => `        const val ${ktName(cap(k))}: String = ${ktStr(v)}`).join("\n")}\n    }`).join("\n")}
}
`;
const copySwift = `// ${copyHeader}
import Foundation

/** Every string on every mocked screen, by screen and id: a screen says Copy.<Screen>.<id>, never the words. */
public enum Copy {
${copyScreens.map((s) => `    public enum ${swName(cap(s.name))} {\n${s.strings.map(([k, v]) => `        public static let ${swName(k)} = ${swStr(v)}`).join("\n")}\n    }`).join("\n")}
}
`;

// A project's own sections (a wordmark, an ambient light, anything its
// tokens carry beyond the standard keys) come from scripts/design/
// generate.local.mjs, which exports extra({ tokens, icons, helpers }) and
// returns { ts, css, kotlin, swift } strings to append. The plugin's file
// stays as shipped, so its fixes still arrive through the sync.
let extra = {};
try {
  const local = await import(new URL("./generate.local.mjs", import.meta.url));
  if (typeof local.extra === "function") extra = (await local.extra({ tokens, icons, helpers: { j, cap, kebab, dbl, argb, ktStr, swStr, accent, family } })) || {};
} catch (e) { if (e.code !== "ERR_MODULE_NOT_FOUND") throw e; }
const withExtra = (text, key) => (extra[key] ? text.replace(/\n*$/, "\n") + "\n" + extra[key].replace(/\n*$/, "\n") : text);

const targets = [];
if (out.ts) targets.push([out.ts, withExtra(ts, "ts")]);
if (out.css) targets.push([out.css, withExtra(css, "css")]);
if (out.kotlin && out.kotlin.path) targets.push([out.kotlin.path, withExtra(kt(out.kotlin.package || "app.ui.theme"), "kotlin")]);
if (out.swift) targets.push([typeof out.swift === "string" ? out.swift : out.swift.path, withExtra(swift, "swift")]);
// The copy modules, only where design/copy/ exists; null leaves one out.
if (existsSync(copyDir)) {
  if (out.copyTs) targets.push([out.copyTs, copyTs]);
  if (out.copyKotlin && out.copyKotlin.path) targets.push([out.copyKotlin.path, copyKt(out.copyKotlin.package || (out.kotlin && out.kotlin.package) || "app.ui.theme")]);
  if (out.copySwift) targets.push([typeof out.copySwift === "string" ? out.copySwift : out.copySwift.path, copySwift]);
}
const check = process.argv.includes("--check");
if (!targets.length) {
  // A project with no app yet names no outputs; the check has nothing to compare.
  if (check) { console.log("design/tokens.json names no outputs yet; nothing to check."); process.exit(0); }
  console.error("design/tokens.json names no outputs; set outputs.ts, outputs.css, outputs.kotlin, outputs.swift or a copy output."); process.exit(2);
}
let stale = false;
for (const [p, text] of targets) {
  const file = join(root, p);
  let cur = "";
  try { cur = readFileSync(file, "utf8"); } catch {}
  if (cur.replace(/\r\n/g, "\n") === text) continue;
  // An output whose folder does not exist yet belongs to a platform not
  // built yet: the check passes it, and a run of the generator writes it.
  if (check && !cur && !existsSync(dirname(file))) { console.log(`${p}: its folder does not exist yet; not checked.`); continue; }
  if (check) { console.error(`${p} is out of date. Run: node scripts/design/generate.mjs`); stale = true; }
  else { mkdirSync(dirname(file), { recursive: true }); writeFileSync(file, text); console.log(`wrote ${p}`); }
}
if (check && !stale) console.log(`Generated design files are current (${targets.length}).`);
process.exit(stale ? 1 : 0);
